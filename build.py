# Bundles the modular source into one self-contained page: dist/index.html
import subprocess, re, pathlib
root = pathlib.Path(__file__).parent
import base64, os
glb = (root/'assets/kaykit.glb').read_bytes()
(root/'js/three/kaykit-data.js').write_text('// generated by build.py from assets/kaykit.glb (CC0 KayKit models)\nexport const KAYKIT_GLB = "' + base64.b64encode(glb).decode() + '";\n')
ch = (root/'assets/kenney-chars.glb').read_bytes()
(root/'js/three/chars-data.js').write_text('// generated by build.py from assets/kenney-chars.glb (CC0 "Mini Characters" by Kenney, kenney.nl)\nexport const CHARS_GLB = "' + base64.b64encode(ch).decode() + '";\n')
hz = (root/'assets/kaykit-heroes.glb').read_bytes()
(root/'js/three/heroes-data.js').write_text('// generated by build.py from assets/kaykit-heroes.glb (CC0 KayKit Adventurers by Kay Lousberg)\nexport const HEROES_GLB = "' + base64.b64encode(hz).decode() + '";\n')
ex = (root/'assets/kaykit-extra.glb').read_bytes()
(root/'js/three/extra-data.js').write_text('// generated by build.py from assets/kaykit-extra.glb (CC0 KayKit Forest + Restaurant Bits by Kay Lousberg)\nexport const EXTRA_GLB = "' + base64.b64encode(ex).decode() + '";\n')
# recorded sound effects (CC0 / public domain, see assets/licenses), embedded as base64 WAV/AAC
sfx = {f.stem: base64.b64encode(f.read_bytes()).decode() for f in sorted([*(root/'assets/sfx').glob('*.wav'), *(root/'assets/sfx').glob('*.m4a')])}
(root/'js/sfx-data.js').write_text('// generated by build.py from assets/sfx (CC0 "Impact Sounds" by Kenney, kenney.nl)\nexport const SFX_WAV = ' + __import__('json').dumps(sfx) + ';\n')
# esbuild: use a local install if there is one, otherwise fall back to npx
local = root/'node_modules/.bin/esbuild'
cmd = [str(local)] if local.exists() else ['npx', '--yes', 'esbuild']
args = ['--bundle', '--format=iife', '--target=es2019', '--minify-syntax', '--minify-whitespace', '--legal-comments=none']
env = {**os.environ}
if local.exists(): env['NODE_PATH'] = str(root/'node_modules')
js = subprocess.run(cmd + [str(root/'js/main.js')] + args, capture_output=True, text=True, env=env)
if js.returncode: print(js.stderr); raise SystemExit(1)
js = js.stdout
css = (root/'css/game.css').read_text()
html = (root/'index.html').read_text()
guard = """<script>window.addEventListener('error',function(e){var l=document.querySelector('#loading p');if(l&&!document.getElementById('loading').classList.contains('gone'))l.textContent='Ops, algo deu errado ao abrir: '+(e.message||'erro');});</script>"""
html = html.replace('<link rel="stylesheet" href="css/game.css">', '<style>\n' + css + '\n</style>\n' + guard)
html = html.replace('<script type="module" src="js/main.js"></script>', '<script>\n' + js.replace('</script', '<\\/script') + '\n</script>')
(root/'dist').mkdir(exist_ok=True)
(root/'dist/index.html').write_text(html)
print(len(html))
